  /// The section [name] belongs in, or [other] when no keyword matches.
  ///
  /// The longest matching phrase wins, so "sour cream" is dairy, "coconut
  /// milk" is pantry, and "garlic powder" is a spice, not produce. Ties go
  /// to the section listed first.
  static StoreSection of(String name) {
    final words = ' ${groceryKey(name)} ';
    StoreSection? best;
    var bestLength = 0;
    for (final (section, phrase) in _phrases) {
      if (phrase.length > bestLength && words.contains(' $phrase ')) {
        best = section;
        bestLength = phrase.length;
      }
    }
    return best ?? other;
  }

  /// The section whose `name` is [name], as stored on an item, or null when
  /// it isn't one of these, such as a section the user typed.
  static StoreSection? byName(String? name) =>
      values.where((section) => section.name == name).firstOrNull;

  static final List<(StoreSection, String)> _phrases = [
    for (final section in values)
      for (final keyword in section.keywords) (section, groceryKey(keyword)),
  ];
